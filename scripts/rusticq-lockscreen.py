def render():
    data = preferences()
    cache = lock_dir()
    image = image_path(data)
    logo = asset_logo(cache)
    content = build_config(data, logo=logo, background=image)
    path = cache / 'hyprlock.conf'
    if path.is_symlink():
        raise RuntimeError('Refusing symlinked lockscreen config')
    temp = cache / 'hyprlock.tmp'
    if temp.exists() or temp.is_symlink():
        temp.unlink()  # only in private directory; atomic replacement below
    fd = os.open(temp, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    with os.fdopen(fd, 'w', encoding='utf8') as out:
        out.write(content)
    temp.replace(path)
    return str(path)


def status():
    data = preferences()
    return dict(ok=True, hyprlock_installed=bool(shutil.which('hyprlock')),
                background=data.get('lockscreenBackground', 'solid'),
                effective_wallpaper=bool(image_path(data)),
                theme='RusticQ', authentication='Hyprlock/PAM')


def lock():
    command = shutil.which('hyprlock')
    if not command:
        return dict(ok=False, message='Hyprlock is not installed. Install it from Settings → Integration → Hyprlock; Omarchy default lockscreen was not changed.')
    config = render()
    # A real Wayland session is required; keep failure explicit.
    if not (os.environ.get('WAYLAND_DISPLAY') or os.environ.get('HYPRLAND_INSTANCE_SIGNATURE')):
        return dict(ok=False, message='No Wayland/Hyprland session detected. RusticQ did not pretend to lock.')
    proc = subprocess.Popen([command, '--config', config], stdin=subprocess.DEVNULL,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                            start_new_session=True, close_fds=True)
    time.sleep(.28)
    rc = proc.poll()
    if rc is not None:
        return dict(ok=False, message='Hyprlock exited immediately (code ' + str(rc) + '). Check PAM, Wayland, and hyprlock logs.')
    return dict(ok=True, message='RusticQ secure lock started via Hyprlock/PAM')


def main(argv):
    if len(argv) != 1 or argv[0] not in ('status', 'render', 'lock'):
        raise ValueError('Usage: rusticq-lockscreen.py status|render|lock')
    if argv[0] == 'status':
        return status()
    if argv[0] == 'render':
        return dict(ok=True, config=render(), message='Theme rendered; screen was NOT locked')
    return lock()


if __name__ == '__main__':
    try:
        result = main(sys.argv[1:])
        print(json.dumps(result, ensure_ascii=False))
        raise SystemExit(0 if result.get('ok') else 1)
    except (OSError, ValueError, RuntimeError, PermissionError) as exc:
        print(json.dumps(dict(ok=False, message=str(exc))))
        raise SystemExit(1)
