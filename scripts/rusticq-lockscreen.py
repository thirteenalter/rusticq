#!/usr/bin/env python3
"""Branded, PAM-backed RusticQ lock screen (hyprlock).

Never handles or stores passwords. Never changes Omarchy's hyprlock.conf or
lock/idle services. `render` / `status` cannot lock the session. Only an
explicit `lock` action starts hyprlock with a generated private theme file.
"""
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
SETTINGS = ROOT / 'user-settings.json'
COLOR = {'orange': 'd65d0e', 'green': 'b8bb26', 'blue': '83a598', 'purple': 'd3869b'}
SAFE_PATH = re.compile(r'\A/[a-zA-Z0-9._/@+ -]+\Z')
SUPPORTED_IMAGES = {'.jpg', '.jpeg', '.png', '.webp'}


def preferences():
    try:
        data = json.loads(SETTINGS.read_text(encoding='utf8'))
        return data if isinstance(data, dict) else {}
    except (OSError, UnicodeError, ValueError):
        return {}


def lock_dir():
    """Use a private directory; reject symbolic links and shared directories."""
    home = Path.home()
    base = home / '.cache' / 'rusticq' / 'lockscreen'
    for path in (home / '.cache', home / '.cache' / 'rusticq', base):
        if path.is_symlink():
            raise RuntimeError('Refusing symlinked lockscreen cache path: ' + str(path))
        if path.exists():
            if not path.is_dir() or path.stat().st_uid != os.getuid():
                raise RuntimeError('Lockscreen cache is not owned by current user')
        else:
            path.mkdir(mode=0o700)
        if path == base:
            path.chmod(0o700)
    return base


def image_path(preferences_data):
    if preferences_data.get('lockscreenBackground') != 'wallpaper':
        return ''
    supplied = preferences_data.get('wallpaperPath', '')
    if not isinstance(supplied, str) or not SAFE_PATH.fullmatch(supplied) or '\n' in supplied:
        return ''
    path = Path(supplied).expanduser()
    try:
        canonical = path.resolve(strict=True)
        home = Path.home().resolve()
        if not canonical.is_relative_to(home):
            return ''
        if (canonical.suffix.lower() in SUPPORTED_IMAGES
                and canonical.is_file() and canonical.stat().st_size <= 20_000_000
                and os.access(canonical, os.R_OK) and SAFE_PATH.fullmatch(str(canonical))):
            return str(canonical)
    except (OSError, RuntimeError):
        pass
    return ''


def asset_logo(cache):
    source = ROOT / 'assets' / 'rusticq-about-icon.png'
    if not source.is_file():
        return ''
    target = cache / 'logo.png'
    # Atomic copy, no symlink follow and no transient half-written asset.
    if target.is_symlink():
        raise RuntimeError('Refusing symlinked lockscreen icon')
    if not SAFE_PATH.fullmatch(str(target)):
        return ''
    temp = cache / 'logo.tmp'
    if temp.is_symlink():
        raise RuntimeError('Refusing symlinked lockscreen temporary icon')
    data = source.read_bytes()
    if len(data) > 2_000_000 or not data.startswith(b'\x89PNG\r\n\x1a\n'):
        raise RuntimeError('Invalid RusticQ lockscreen logo asset')
    fd = os.open(temp, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
    except BaseException:
        temp.unlink(missing_ok=True)
        raise
    temp.replace(target)
    return str(target)


